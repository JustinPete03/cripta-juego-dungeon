def buscarSprite(nombre):
    for n, cuerpo in zip(NOMBRES, CUERPOS):
        if n == nombre:
            return cuerpo
    return HEROE


def _celdas(cuerpo, nombre=""):
    matriz = []
    for fila in cuerpo:
        linea = []
        for ch in fila.ljust(MEDIDA, ".")[:MEDIDA]:
            linea.append(PALETA.get(ch))
        matriz.append(linea)
    while len(matriz) < MEDIDA:
        matriz.append([None] * MEDIDA)
    return matriz[:MEDIDA]


def construir(pg, nombre=None, escala=3):
    if isinstance(pg, str):
        escala = nombre if isinstance(nombre, int) else 3
        nombre = pg
        pg = pygame

    cuerpo = buscarSprite(nombre)
    celdas = _celdas(cuerpo, nombre)
    base = pg.Surface((MEDIDA, MEDIDA), pg.SRCALPHA)
    for y in range(MEDIDA):
        for x in range(MEDIDA):
            tono = celdas[y][x]
            if tono is not None:
                base.set_at((x, y), (*tono, 255))
            else:
                for dx, dy in ((-1, 0), (1, 0), (0, -1), (0, 1)):
                    nx, ny = x + dx, y + dy
                    if 0 <= nx < MEDIDA and 0 <= ny < MEDIDA and celdas[ny][nx] is not None:
                        base.set_at((x, y), (*CONTORNO, 255))
                        break
    lado = MEDIDA * escala
    return pg.transform.scale(base, (lado, lado))


def construirTodos(pg=None, escala=3):
    if pg is None or isinstance(pg, int):
        escala = pg if isinstance(pg, int) else 3
        pg = pygame
    return [(nombre, escala, construir(pg, nombre, escala)) for nombre in NOMBRES]